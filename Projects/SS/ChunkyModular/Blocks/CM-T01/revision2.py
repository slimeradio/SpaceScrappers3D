def octagonal_tube(name,loc,outer,inner,depth,mat):
    obj=B.ring(name,loc,outer,inner,depth,mat,'Y')
    # Keep a circular 96-sided bore; shape only the outer two loops into 8 flats.
    for v in list(obj.data.vertices)[:2*G['CYL_SEGMENTS']]:
        x=v.co.x-loc[0]; z=v.co.z-loc[2]; angle=math.atan2(z,x)
        radius=outer*math.cos(math.pi/8)/math.cos((angle+math.pi/8)%(math.pi/4)-math.pi/8)
        v.co.x=loc[0]+radius*math.cos(angle); v.co.z=loc[2]+radius*math.sin(angle)
    return obj

