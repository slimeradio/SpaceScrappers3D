def textured_metals():
    B.TEX.mkdir(parents=True,exist_ok=True)
    rng=np.random.default_rng(190)
    n=768; yy,xx=np.mgrid[:n,:n]
    grain=rng.normal(0,.007,(n,n))
    grime=(np.sin(xx*.017+np.sin(yy*.013)*2)*np.cos(yy*.021)+1)*.5
    chips=np.zeros((n,n),np.float32)
    for i in range(600):
        x,y=rng.integers(5,n-40,2); length=int(rng.integers(2,38))
        chips[y:y+int(rng.integers(1,3)),x:x+length]=rng.uniform(.5,1)
    for i in range(35):
        x,y=rng.integers(10,n-35,2); w,h=rng.integers(4,22,2)
        mask=rng.random((h,w))>.28
        chips[y:y+h,x:x+w]=np.maximum(chips[y:y+h,x:x+w],mask.astype(float)*rng.uniform(.65,1))
    palette={
      'orange':((.70,.29,.065),.05,.72), 'ivory':((.59,.565,.48),.05,.76),
      'graphite':((.20,.22,.24),.88,.57), 'steel':((.43,.46,.48),.95,.39),
      'rubber':((.033,.037,.038),0,.88), 'marking':((.50,.50,.46),.4,.7),
      'weld':((.29,.29,.26),.88,.62),'oxide':((.22,.095,.035),.12,.91)}
    settings={}
    for name,(col,metal,rough) in palette.items():
        paint=name in ('orange','ivory')
        wear=chips if paint else chips*.30
        albedo=np.clip(np.array(col)[None,None,:]*(1+grain[:,:,None]*2-grime[:,:,None]*.20),0,1)
        exposed=np.array([.34,.365,.38])
        albedo=albedo*(1-wear[:,:,None])+exposed*wear[:,:,None]
        # Generated byte images store authored sRGB values; shader decodes them.
        im=B.image_file(name+'_basecolor',albedo)
        rm=np.clip(rough+grain*2+grime*.08-wear*.22,.26,.95)
        mm=np.clip(metal+wear*(.94-metal),0,1)
        ri=B.image_file(name+'_roughness',rm,True)
        mi=B.image_file(name+'_metallic',mm,True)
        normals=np.zeros((n,n,3),np.float32); normals[:,:,:2]=.5
        normals[:,:,0]+=np.gradient(grain-chips*.01,axis=1)*.30
        normals[:,:,1]+=np.gradient(grain-chips*.01,axis=0)*.30
        normals[:,:,2]=1
        ni=B.image_file(name+'_normal',normals,True)
        mat=bpy.data.materials.new('CM.'+name); mat.use_nodes=True
        mat.diffuse_color=(*np.where(np.array(col)<=.04045,np.array(col)/12.92,((np.array(col)+.055)/1.055)**2.4),1)
        ns=mat.node_tree.nodes; ls=mat.node_tree.links; p=ns.get('Principled BSDF')
        p.inputs['Coat Weight'].default_value=0
        for idx,(image,socket) in enumerate([(im,'Base Color'),(ri,'Roughness'),(mi,'Metallic')]):
            node=ns.new('ShaderNodeTexImage'); node.image=image; node.location=(-600,220-idx*220)
            ls.new(node.outputs['Color'],p.inputs[socket])
        node=ns.new('ShaderNodeTexImage'); node.image=ni; node.location=(-600,-440)
        normal=ns.new('ShaderNodeNormalMap'); normal.inputs['Strength'].default_value=.13
        ls.new(node.outputs['Color'],normal.inputs['Color']); ls.new(normal.outputs['Normal'],p.inputs['Normal'])
        B.MATS[name]=mat
        settings[name]={'base_color_srgb':col,'base_color':im.name+'.png','roughness_source':ri.name+'.png','metallic_source':mi.name+'.png','normal':ni.name+'.png','finish':'chipped matte paint over steel' if paint else 'exposed rough metal' if metal>.5 else 'nonmetal'}
    for name,color,strength in [('amber',(1,.29,.025),1.7),('cyan',(.03,.40,.7),1.4)]:
        mat=bpy.data.materials.new('CM.'+name); mat.use_nodes=True
        p=mat.node_tree.nodes.get('Principled BSDF'); p.inputs['Base Color'].default_value=(*color,1)
        p.inputs['Emission Color'].default_value=(*color,1); p.inputs['Emission Strength'].default_value=strength
        p.inputs['Roughness'].default_value=.45; B.MATS[name]=mat
    B.js(B.TEX/'materials.json',{'version':'2.0.0','textures':'768x768 PNG; sRGB albedo, non-color roughness / metallic / tangent normal',
        'materials':settings,'emission':{'amber':{'linear_rgb':[1,.29,.025],'blender_strength':1.7},'cyan':{'linear_rgb':[.03,.40,.7],'blender_strength':1.4}},
        'note':'Independent roughness and metallic maps per finish. Authoring contract, not a game shader.'})

def seam(points,radius=.009,smooth=False):
    cv=bpy.data.curves.new('weld bead','CURVE'); cv.dimensions='3D'; cv.resolution_u=24 if smooth else 2; cv.bevel_depth=radius; cv.bevel_resolution=8
    sp=cv.splines.new('BEZIER' if smooth else 'POLY')
    if smooth:
        sp.bezier_points.add(len(points)-1)
        for p,co in zip(sp.bezier_points,points): p.co=co; p.handle_left_type='AUTO'; p.handle_right_type='AUTO'
    else:
        sp.points.add(len(points)-1)
        for p,co in zip(sp.points,points): p.co=(*co,1)
    obj=bpy.data.objects.new('weld seam',cv); G['ASSET'].objects.link(obj); obj.parent=G['ROOT']; cv.materials.append(B.MATS['weld'])
    bpy.context.view_layer.objects.active=obj; bpy.ops.object.select_all(action='DESELECT'); obj.select_set(True); bpy.ops.object.convert(target='MESH')
    return obj

