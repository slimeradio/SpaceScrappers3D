def scaled_builder(pid,fn):
    def build():
        fn()
        if pid=='cm-receiver':
            for x in [-.86,.86]: B.box('thick upper shoulder armor',(x,.14,.78),(.41,1.33,.20),'orange',.035)
            for x in [-.94,.94]: seam([(x,-.43,.705),(x,.60,.705)],.009)
        if pid in ('cm-cheek-left','cm-cheek-right'):
            sign=-1 if pid.endswith('left') else 1
            B.box('exposed forward edge',(sign*.144,-.80,.12),(.024,.07,.55),'steel',.009)
        scale=SCALES.get(pid,(1,1,1))
        for o in list(G['ASSET'].objects):
            if o.type!='MESH': continue
            o.location=tuple(o.location[i]*scale[i] for i in range(3))
            o.scale=tuple(o.scale[i]*scale[i] for i in range(3))
            bpy.context.view_layer.objects.active=o; bpy.ops.object.select_all(action='DESELECT'); o.select_set(True)
            bpy.ops.object.transform_apply(location=False,rotation=False,scale=True)
    return build

